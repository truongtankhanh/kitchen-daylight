// Design token tool. No dependencies.
//   node tokens.mjs build   -> writes tokens.css from tokens.json
//   node tokens.mjs check   -> checks WCAG contrast of token pairs; exits 1 on any failure
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function themeBlock(mode) {
  const lines = [];
  for (const [k, v] of Object.entries(tokens.color[mode])) lines.push(`  --color-${kebab(k)}: ${v};`);
  lines.push(`  --glass-bg: ${tokens.glass[mode].bg};`);
  lines.push(`  --glass-border: ${tokens.glass[mode].border};`);
  lines.push(`  --elevation: ${tokens.elevation[mode]};`);
  lines.push(`  color-scheme: ${mode};`);
  return lines.join('\n');
}

function build() {
  const t = tokens;
  const out = [];
  out.push('/* Generated by tokens.mjs from tokens.json. Do not edit by hand. */');
  out.push(':root,\n:root[data-theme="light"],\n[data-theme="light"] {');
  out.push(themeBlock('light'));
  out.push('}');
  out.push('@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {');
  out.push(themeBlock('dark').split('\n').map((l) => '  ' + l).join('\n'));
  out.push('  }\n}');
  out.push(':root[data-theme="dark"],\n[data-theme="dark"] {');
  out.push(themeBlock('dark'));
  out.push('}');
  out.push(':root {');
  out.push(`  --glass-blur: ${t.glass.blur};`);
  t.space.forEach((v, i) => out.push(`  --space-${i + 1}: ${v}px;`));
  for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v}px;`);
  out.push(`  --touch-target: ${t.touchTarget}px;`);
  out.push(`  --font-family: ${t.font.family}, ${t.font.fallback};`);
  for (const [group, scale] of Object.entries({ m: t.font.mobile, a: t.font.admin })) {
    for (const [k, v] of Object.entries(scale)) {
      out.push(`  --${group}-${kebab(k)}-size: ${v.size}px;`);
      out.push(`  --${group}-${kebab(k)}-line: ${v.line}px;`);
      out.push(`  --${group}-${kebab(k)}-weight: ${v.weight};`);
    }
  }
  out.push(`  --motion-fast: ${t.motion.fastMs}ms;`);
  out.push(`  --motion-base: ${t.motion.baseMs}ms;`);
  out.push('}');
  out.push('@media (prefers-reduced-motion: reduce) {\n  :root { --motion-fast: 100ms; --motion-base: 100ms; }\n}');
  writeFileSync(join(here, 'tokens.css'), out.join('\n') + '\n');
  console.log('wrote tokens.css');
}

// WCAG 2.x relative luminance and contrast ratio
function luminance(hex) {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const f = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

// [foreground token, background token, required ratio, note]
const PAIRS = [
  ['text', 'bg', 4.5, 'body text'],
  ['text', 'surface', 4.5, 'body text on cards'],
  ['text', 'surfaceVariant', 4.5, 'text on chips'],
  ['textSecondary', 'bg', 4.5, 'supporting text'],
  ['textSecondary', 'surface', 4.5, 'supporting text on cards'],
  ['textSecondary', 'surfaceVariant', 4.5, 'supporting text on chips'],
  ['onPrimary', 'primary', 4.5, 'button label'],
  ['onPrimary', 'primaryPressed', 4.5, 'button label, pressed'],
  ['primaryStrong', 'bg', 4.5, 'primary text or icon'],
  ['primaryStrong', 'surface', 4.5, 'primary text or icon on cards'],
  ['primaryStrong', 'surfaceVariant', 4.5, 'primary text or icon on chips'],
  ['primaryStrong', 'primaryContainer', 4.5, 'active tab icon on its pill'],
  ['onPrimaryContainer', 'primaryContainer', 4.5, 'selected chip'],
  ['onSecondary', 'secondary', 4.5, 'secondary button label'],
  ['secondary', 'bg', 4.5, 'secondary text or icon'],
  ['secondary', 'surface', 4.5, 'secondary text or icon on cards'],
  ['onSecondaryContainer', 'secondaryContainer', 4.5, 'open and verified pill'],
  ['warning', 'warningContainer', 4.5, 'warning pill'],
  ['warning', 'surface', 4.5, 'warning text'],
  ['error', 'surface', 4.5, 'error text'],
  ['error', 'bg', 4.5, 'error text on screen'],
  ['outline', 'surface', 3.0, 'input boundary'],
  ['outline', 'bg', 3.0, 'control boundary'],
  ['star', 'surface', 3.0, 'rating star'],
  ['star', 'bg', 3.0, 'rating star on screen'],
  ['star', 'surfaceVariant', 3.0, 'rating star on chips'],
];

function check() {
  let failures = 0;
  for (const mode of ['light', 'dark']) {
    console.log(`\n== ${mode}`);
    for (const [fg, bg, need, note] of PAIRS) {
      const c = contrast(tokens.color[mode][fg], tokens.color[mode][bg]);
      const ok = c >= need;
      if (!ok) failures += 1;
      console.log(`${ok ? 'OK  ' : 'FAIL'} ${fg} on ${bg}: ${c.toFixed(2)} (need ${need}) - ${note}`);
    }
  }
  console.log(failures === 0 ? '\nAll pairs pass.' : `\n${failures} pair(s) fail.`);
  process.exit(failures === 0 ? 0 : 1);
}

const cmd = process.argv[2];
if (cmd === 'build') build();
else if (cmd === 'check') check();
else {
  console.error('usage: node tokens.mjs <build|check>');
  process.exit(2);
}
